import { Construct } from 'constructs';
import * as s3 from 'aws-cdk-lib/aws-s3';
import * as cloudtrail from 'aws-cdk-lib/aws-cloudtrail';
import { RemovalPolicy } from 'aws-cdk-lib';
import * as cdk from 'aws-cdk-lib';
import { PolicyStatement, Effect, ServicePrincipal } from 'aws-cdk-lib/aws-iam';

/**
 * Single-Region CloudTrail trail for management events (read and write).
 *
 * Read events (ReadWriteType All) are required so that EventBridge receives
 * read-only management events such as kms:Sign, which the tak-infra Root CA
 * alert relies on.
 *
 * The log bucket uses S3-managed encryption (not the BaseInfra KMS key) and is
 * always RETAIN so audit logs survive stack deletion. Its name is generated by
 * CloudFormation so a retained bucket never blocks a redeploy.
 */
export function createCloudTrailResources(scope: Construct, stackName: string, logRetentionDays: number) {
  const cloudTrailLogsBucket = new s3.Bucket(scope, 'CloudTrailLogsBucket', {
    encryption: s3.BucketEncryption.S3_MANAGED,
    enforceSSL: true,
    blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
    objectOwnership: s3.ObjectOwnership.BUCKET_OWNER_ENFORCED,
    removalPolicy: RemovalPolicy.RETAIN,
    lifecycleRules: [{
      id: 'ExpireCloudTrailLogs',
      expiration: cdk.Duration.days(logRetentionDays),
      enabled: true
    }]
  });

  // Trail name is set explicitly so the ARN can be used in the bucket policy
  // conditions without a circular reference between trail and policy.
  const trailName = `${stackName}-ManagementEvents`;
  const trailArn = cdk.Stack.of(scope).formatArn({
    service: 'cloudtrail',
    resource: 'trail',
    resourceName: trailName,
  });

  // Confused-deputy protection: only this trail in this account may write
  const sourceConditions = {
    'aws:SourceArn': trailArn,
    'aws:SourceAccount': cdk.Aws.ACCOUNT_ID,
  };

  cloudTrailLogsBucket.addToResourcePolicy(new PolicyStatement({
    sid: 'AWSCloudTrailAclCheck',
    effect: Effect.ALLOW,
    principals: [new ServicePrincipal('cloudtrail.amazonaws.com')],
    actions: ['s3:GetBucketAcl'],
    resources: [cloudTrailLogsBucket.bucketArn],
    conditions: { StringEquals: sourceConditions }
  }));
  cloudTrailLogsBucket.addToResourcePolicy(new PolicyStatement({
    sid: 'AWSCloudTrailWrite',
    effect: Effect.ALLOW,
    principals: [new ServicePrincipal('cloudtrail.amazonaws.com')],
    actions: ['s3:PutObject'],
    resources: [`${cloudTrailLogsBucket.bucketArn}/AWSLogs/${cdk.Aws.ACCOUNT_ID}/*`],
    conditions: {
      StringEquals: {
        ...sourceConditions,
        's3:x-amz-acl': 'bucket-owner-full-control'
      }
    }
  }));

  const trail = new cloudtrail.CfnTrail(scope, 'ManagementEventsTrail', {
    trailName,
    s3BucketName: cloudTrailLogsBucket.bucketName,
    isLogging: true,
    isMultiRegionTrail: false,
    includeGlobalServiceEvents: false,
    enableLogFileValidation: true,
    eventSelectors: [{
      readWriteType: 'All',
      includeManagementEvents: true,
    }],
  });
  // CloudTrail validates bucket access at creation time
  trail.node.addDependency(cloudTrailLogsBucket.policy!);

  return { cloudTrailLogsBucket, trail };
}
